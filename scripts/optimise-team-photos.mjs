/**
 * Optimise the team headshots and regenerate src/content/team-photos.ts.
 *
 *   node scripts/optimise-team-photos.mjs <source-dir>
 *
 * The sources are the firm's own headshots from their previous site. They are
 * square, colour, and shot on a light-blue backdrop; the old site rendered them
 * black-and-white with a CSS `filter: grayscale(1)`. We bake the greyscale into
 * the file instead, so the treatment is consistent everywhere, costs nothing to
 * paint, and can't flash colour before styles apply. Rec709Luma matches what the
 * CSS filter was doing.
 *
 * 900px square covers the largest display slot (a ~430px card at 2× DPR); the
 * modal badge is far smaller and `next/image` derives it from the same file.
 *
 * Requires ImageMagick (`magick`) on PATH. Re-run only when the source
 * headshots change — the output is committed.
 */

import { execFileSync } from "node:child_process";
import { mkdirSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";

/** Longest edge of the committed headshot. */
const MAX_EDGE = 900;
const QUALITY = 82;

const OUT_DIR = "public/images/team";
const REGISTRY = "src/content/team-photos.ts";

const sourceDir = process.argv[2];
if (!sourceDir) {
  console.error("usage: node scripts/optimise-team-photos.mjs <source-dir>");
  process.exit(1);
}

const magick = (args) => execFileSync("magick", args, { encoding: "buffer" });

mkdirSync(OUT_DIR, { recursive: true });

const sources = readdirSync(sourceDir)
  .filter((file) => /\.(jpe?g|png)$/i.test(file))
  .sort();

let before = 0;
let after = 0;
const entries = [];

for (const file of sources) {
  const slug = basename(file).replace(/\.[^.]+$/, "");
  const source = join(sourceDir, file);
  const out = join(OUT_DIR, `${slug}.jpg`);

  before += statSync(source).size;

  magick([
    source,
    "-auto-orient",
    "-colorspace",
    "sRGB",
    "-resize",
    `${MAX_EDGE}x${MAX_EDGE}>`,
    // Match the old site's `filter: grayscale(1)` (Rec. 709 luma on the
    // non-linear sRGB values), then keep a 3-channel sRGB JPEG so next/image's
    // AVIF/WebP negotiation behaves the same as for the rest of the photography.
    "-grayscale",
    "Rec709Luma",
    "-colorspace",
    "sRGB",
    "-strip",
    "-interlace",
    "JPEG",
    "-sampling-factor",
    "4:2:0",
    "-quality",
    String(QUALITY),
    out,
  ]);

  after += statSync(out).size;

  const [width, height] = magick(["identify", "-format", "%w %h", out])
    .toString()
    .split(" ")
    .map(Number);

  // Tiny inline preview for next/image `placeholder="blur"` — same approach as
  // the main photography registry.
  const blur = magick([
    out,
    "-resize",
    "10x10>",
    "-strip",
    "-quality",
    "40",
    "jpeg:-",
  ]);

  entries.push({
    slug,
    width,
    height,
    blurDataURL: `data:image/jpeg;base64,${blur.toString("base64")}`,
  });
}

const kb = (bytes) => `${(bytes / 1024).toFixed(1)} kB`;
console.log(
  `${entries.length} headshots: ${kb(before)} -> ${kb(after)} (${(
    (1 - after / before) *
    100
  ).toFixed(1)}% smaller)`,
);

const body = entries
  .map(
    (entry) => `  "${entry.slug}": {
    src: "/images/team/${entry.slug}.jpg",
    width: ${entry.width},
    height: ${entry.height},
    blurDataURL:
      "${entry.blurDataURL}",
  },`,
  )
  .join("\n");

writeFileSync(
  REGISTRY,
  `/**
 * Team headshots — GENERATED by scripts/optimise-team-photos.mjs. Do not edit.
 *
 * The firm's own photography, migrated from their previous site: square,
 * ${MAX_EDGE}px, greyscale baked in (the old site applied it as a CSS filter),
 * EXIF stripped, mozjpeg q${QUALITY}. Served through next/image by <Headshot>.
 *
 * Keyed by the team member's \`id\` in site.ts. A member with no entry here
 * falls back to the initials <Monogram>.
 */

export interface TeamPhoto {
  src: string;
  width: number;
  height: number;
  /** Tiny inline preview for next/image \`placeholder="blur"\` (no flash). */
  blurDataURL: string;
}

export const teamPhotos: Record<string, TeamPhoto> = {
${body}
};

export const teamPhoto = (id: string): TeamPhoto | undefined => teamPhotos[id];
`,
);

console.log(`wrote ${REGISTRY}`);
